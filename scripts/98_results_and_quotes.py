"""Phase 11: results/RESULTS.md (every number the paper may quote) and results/QUOTES.md (every Portuguese quotation).

RESULTS.md: each number of config/paper_numbers.yaml is read from its pinned source file
(config/paper_assets.yaml `sources`) by its selector, formatted, and listed with the file, the selector, and
the script and run manifest that wrote the file as it is now (found by its sha256 in the run manifests).
No number is typed by hand; a selector that matches no row, or more than one, stops the script.

QUOTES.md: the Portuguese quotations of the B3 quotes, the A3 example answers, the A4 examples and the prompt
specifications, each with its source file and location, the original, the English translation and whether
The author has reviewed that translation (ground rule 10). Review state comes from the quotes' source files
(B3's translations were approved on 2026-10-06; the others are marked as drafts there) and from the newest
results/quotes_review.xlsx, in which the author marks `reviewed` (1) and may write a corrected translation.

Outputs:
  results/RESULTS.md, results/QUOTES.md    regenerated on every run (generated indexes; git keeps their history)
  results/quotes_review.xlsx               with --review-sheet: a new version (never overwritten) carrying over the
                                           marks of the previous one
  results/98_results_and_quotes.manifest.json

Usage:
  uv run python scripts/98_results_and_quotes.py [--review-sheet] [--allow-stale]
"""

from __future__ import annotations

import argparse
import re
import string
from pathlib import Path

import numpy as np
import pandas as pd

from jm_eval import paper as P
from jm_eval.io import latest_artefact_path, load_config, new_artefact_path, resolve
from jm_eval.manifest import RunManifest

SCRIPT = "98_results_and_quotes"
HEADER_NOTE = ("Generated by `scripts/98_results_and_quotes.py` from `config/paper_numbers.yaml` and the files pinned in "
               "`config/paper_assets.yaml`. Do not edit by hand: change the config and run the script again.")


# =========================================================================================== numbers

class NumberFormatter(string.Formatter):
    """Format specs of config/paper_numbers.yaml (see its header); rounding is half up on the value as written."""

    def format_field(self, value, spec):
        if isinstance(value, (np.generic,)):
            value = value.item()
        if isinstance(value, str) or isinstance(value, bool) or value is None:
            return str(value)
        if spec == "":
            return str(int(value)) if float(value).is_integer() else str(value)
        if spec == "p":
            return P.pval(value)
        if spec in ("usd", "usd2"):
            return P.usd(value, 2 if spec == "usd2" else 3)
        if spec in ("%0", "%1"):
            return P.pct(value, int(spec[1]))
        if spec == "d":
            return str(int(P.rounded(value, 0)))
        if spec == ",.0f":
            return f"{int(P.rounded(value, 0)):,}"
        m = re.fullmatch(r"(\+)?\.(\d)f", spec)
        if m:
            return P.signed(value, int(m.group(2))) if m.group(1) else P.f(value, int(m.group(2)))
        return format(value, spec)


FMT = NumberFormatter()


def _match(frame: pd.DataFrame, where: dict) -> pd.DataFrame:
    mask = pd.Series(True, index=frame.index)
    for col, val in (where or {}).items():
        if col not in frame.columns:
            raise KeyError(f"no column {col!r}")
        if val is None:
            mask &= frame[col].isna()
        else:
            mask &= frame[col].astype(str).str.lower() == str(val).lower()
    return frame[mask]


def _json_get(obj, path: str):
    for part in path.split("."):
        if isinstance(obj, list):
            obj = obj[int(part)]
        else:
            obj = obj[part]
    return obj


def evaluate(spec: dict, S: P.Sources, values: dict) -> tuple[list, str, str]:
    """(raw values, formatted value, selector text) of one number."""
    if "expr" in spec:
        raw = eval(spec["expr"], {"__builtins__": {}, "sum": sum, "min": min, "max": max, "round": round}, {"v": values})
        raw = raw if isinstance(raw, list) else [raw]
        return raw, FMT.format(spec["fmt"], *raw), f"computed: {spec['expr']}"
    src = spec["source"]
    path = S.path(src, f"number:{spec['id']}")
    if path.suffix == ".json":
        keys = spec["key"] if isinstance(spec["key"], list) else [spec["key"]]
        raw = [_json_get(S.json(src), k) for k in keys]
        selector = ", ".join(keys)
    else:
        frame = S.excel(src, spec["sheet"]) if path.suffix == ".xlsx" else S.csv(src)
        rows = _match(frame, spec.get("where", {}))
        cols = spec["value"] if isinstance(spec["value"], list) else [spec["value"]]
        if spec.get("agg"):
            if not len(rows):
                raise ValueError(f"{spec['id']}: no row matches {spec.get('where')}")
            raw = [getattr(rows[c].astype(float), spec["agg"])() for c in cols]
        else:
            if len(rows) != 1:
                raise ValueError(f"{spec['id']}: {len(rows)} rows match {spec.get('where')} in {P.rel(path)}")
            raw = [rows.iloc[0][c] for c in cols]
        where = ", ".join(f"{k}={v}" for k, v in (spec.get("where") or {}).items()) or "all rows"
        selector = (f"sheet {spec['sheet']}: " if "sheet" in spec else "") + f"{where} → {spec.get('agg', '') + ' ' if spec.get('agg') else ''}{', '.join(cols)}"
    raw = [r.item() if isinstance(r, np.generic) else r for r in raw]
    return raw, FMT.format(spec["fmt"], *raw), selector


def build_results(S: P.Sources, numbers_cfg: dict, index: dict) -> tuple[str, int]:
    values: dict[str, object] = {}
    lines = ["# Results the paper may quote", "", HEADER_NOTE, "",
             "Each section opens with the claim its numbers support and the limits the paper should state with it. "
             "Values are rounded half up as the paper prints them. 'Source' is the file and the selector that the value "
             "is read from; the files' producing scripts and run manifests are listed under each table. Version labels "
             "follow ground rule 9 (v2.6 and v2.7 appear only where A4 compares the drafting pipeline before and after "
             "the fact controls).", ""]
    lines += ["## Contents", ""] + [f"- [{s['title']}](#{_anchor(s['title'])})" for s in numbers_cfg["sections"]]
    lines += ["- [Results that carry no claim](#results-that-carry-no-claim)", ""]
    count = 0
    for section in numbers_cfg["sections"]:
        lines += [f"## {section['title']}", "", f"**Claim.** {section['claim']}", ""]
        if section.get("caveats"):
            lines += ["**State with it.**", ""] + [f"- {c}" for c in section["caveats"]] + [""]
        absent = sorted({spec["source"] for spec in section["numbers"] if spec.get("source") in S.missing_optional()})
        if absent:
            lines += [f"Not rebuilt in this copy: {S.optional[a]} (`{a}`)." for a in absent] + [""]
            continue
        lines += ["| ID | Number | Value | Source |", "| --- | --- | --- | --- |"]
        used = []
        for spec in section["numbers"]:
            raw, shown, selector = evaluate(spec, S, values)
            values[spec["id"]] = raw[0] if len(raw) == 1 else raw
            src = P.rel(S.paths[spec["source"]]) if "source" in spec else "—"
            if "source" in spec and spec["source"] not in used:
                used.append(spec["source"])
            lines.append(f"| `{spec['id']}` | {_cell(spec['text'])} | **{_cell(shown)}** | `{src}`: {_cell(selector)} |")
            count += 1
        lines += ["", "Sources:", ""]
        for src in used:
            path = S.paths[src]
            prod = P.producer(path, index)
            note = S.cfg.get("source_notes", {}).get(src, "no run manifest records this file as it is now")
            lines.append(f"- `{P.rel(path)}`: " + (f"written by `scripts/{prod[1]}.py`, run manifest `{prod[0]}`" if prod else note))
        lines.append("")
    lines += ["## Results that carry no claim", "",
              "Left out of the paper on the rule that every claim must be well supported and that analyses supporting no claim "
              "are dropped rather than reported weakly (DECISIONS, 2026-10-11):", ""]
    lines += [f"- {item}" for item in numbers_cfg.get("not_claimed", [])] + [""]
    return "\n".join(lines), count


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _anchor(title: str) -> str:
    a = re.sub(r"[^\w\- ]", "", title.lower()).strip().replace(" ", "-")
    return a


# =========================================================================================== quotes

def quotes_b3(S: P.Sources) -> list[dict]:
    t = S.csv("b3_quotes", "quotes")
    return [{"quote_id": r["quote_id"], "source": P.rel(S.paths["b3_quotes"]),
             "location": f"expert {r['expert']}; themes {r['themes']} ({r['theme_labels']})", "kind": "B3 expert quote",
             "original_pt": r["quote_pt"], "translation_en": r["quote_en"],
             "translation_by": "approved by the author (2026-10-06)", "reviewed": True} for _, r in t.iterrows()]


def quotes_prompt_specs(S: P.Sources) -> list[dict]:
    text = S.text("prompt_specs", "quotes")
    out, heading, n = [], "", 0
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if line.startswith("### "):
            heading, n = line[4:].strip(), 0
            continue
        m = re.match(r"- \*\*Excerpt([^*]*)\*\*\s*«(.+)»\s*$", line)
        if not m or "EN" in m.group(1) or re.search(r"\bEN\b", heading):
            continue                      # an English prompt is not a Portuguese quotation
        en = re.match(r'\s+- EN:\s*"(.+)"\s*$', lines[i + 1]) if i + 1 < len(lines) else None
        n += 1
        pid = heading.split(" ")[0] if re.match(r"v\d\.\d", heading) else re.sub(r"\W+", "-", heading.split(" (")[0]).strip("-")
        out.append({"quote_id": f"PS-{pid}-{n}", "source": P.rel(S.paths["prompt_specs"]), "location": heading,
                    "kind": "prompt excerpt (version 2.2 / version 1 as tagged)", "original_pt": m.group(2),
                    "translation_en": en.group(1) if en else "", "translation_by": "draft (Phase 2), not reviewed",
                    "reviewed": False})
    return out


def quotes_a3(S: P.Sources) -> list[dict]:
    text = S.text("a3_examples", "quotes")
    out = []
    for block in re.split(r"(?m)^### ", text)[1:]:
        head = block.splitlines()[0].strip()
        qid = head.split(" ")[0]
        q_pt = re.search(r"\*\*Question \(pt\):\*\*\s*(.+)", block)
        q_en = re.search(r"\*\*Question \(en[^)]*\):\*\*\s*(.+)", block)
        common = {"source": P.rel(S.paths["a3_examples"]), "translation_by": "Mistral Medium 3 draft, not reviewed", "reviewed": False}
        if q_pt:
            out.append({"quote_id": f"A3-{qid}-question", "location": head, "kind": "A3 question",
                        "original_pt": q_pt.group(1).strip(), "translation_en": q_en.group(1).strip() if q_en else "", **common})
        parts = re.split(r"\*\*Answer \(en[^*]*\*\*", block)
        pt_part = parts[0].split("**Answer (pt):**")[-1] if "**Answer (pt):**" in parts[0] else ""
        pt_paras, en_paras = _quoted_paragraphs(pt_part), _quoted_paragraphs(parts[1]) if len(parts) > 1 else []
        if len(pt_paras) != len(en_paras):              # cannot pair by paragraph: the whole answer is one quotation
            pt_paras, en_paras = ["\n\n".join(pt_paras)], ["\n\n".join(en_paras)]
        for k, (pt, en) in enumerate(zip(pt_paras, en_paras), 1):
            out.append({"quote_id": f"A3-{qid}-p{k:02d}", "location": f"{head}, answer paragraph {k}", "kind": "A3 chatbot answer",
                        "original_pt": pt, "translation_en": en, **common})
    return out


def _quoted_paragraphs(text: str) -> list[str]:
    paras, cur = [], []
    for line in text.splitlines():
        if line.startswith(">"):
            body = line[1:].strip()
            if body:
                cur.append(body)
            elif cur:
                paras.append(" ".join(cur)); cur = []
        elif cur:
            paras.append(" ".join(cur)); cur = []
    if cur:
        paras.append(" ".join(cur))
    return paras


INLINE = re.compile(r'"([^"]{8,})"\s*\((?:[^()*]*?;\s*)?\*([^*]+)\*\)')


def quotes_a4(S: P.Sources) -> list[dict]:
    text = S.text("a4_examples", "quotes")
    out, section, label, n = [], "", "", 0
    lines = text.splitlines()
    common = {"source": P.rel(S.paths["a4_examples"]), "translation_by": "draft, not reviewed", "reviewed": False, "kind": "A4 draft excerpt"}
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("## "):
            section, n = line[3:].strip(), 0
            sec_id = section.split(".")[0]
        elif re.fullmatch(r"\*\*.+:\*\*", line.strip()):
            label = line.strip().strip("*").rstrip(":")
        elif line.startswith(">"):
            block = []
            while i < len(lines) and lines[i].startswith(">"):
                block.append(lines[i][1:].strip()); i += 1
            while i < len(lines) and not lines[i].strip():
                i += 1
            en = lines[i].strip() if i < len(lines) and lines[i].strip().startswith("*") else ""
            n += 1
            out.append({"quote_id": f"A4-{sec_id}-{n:02d}", "location": f"{section}; {label}",
                        "original_pt": " ".join(b for b in block if b), "translation_en": en.strip("*").strip(), **common})
            continue
        else:
            for m in INLINE.finditer(line):
                where = re.search(r'\(([^()*]*?);\s*\*', m.group(0))
                n += 1
                out.append({"quote_id": f"A4-{sec_id}-{n:02d}", "location": f"{section}" + (f"; {where.group(1)}" if where else ""),
                            "original_pt": m.group(1), "translation_en": m.group(2).strip(), **common})
        i += 1
    return out


REVIEW_COLUMNS = ["quote_id", "kind", "source", "location", "original_pt", "translation_en", "translation_by",
                  "reviewed", "translation_en_reviewed", "comment"]


def apply_review(quotes: list[dict], sheet: Path | None) -> int:
    """Marks of the author's review sheet: reviewed = 1, and a corrected translation if one is written.
    A mark applies only while the original is unchanged (a changed quotation must be reviewed again)."""
    if not sheet or not sheet.exists():
        return 0
    marks = pd.read_excel(sheet).set_index("quote_id")
    applied = 0
    for q in quotes:
        if q["quote_id"] not in marks.index:
            continue
        m = marks.loc[q["quote_id"]]
        if str(m["original_pt"]).strip() != str(q["original_pt"]).strip():
            continue
        fixed = m.get("translation_en_reviewed")
        if isinstance(fixed, str) and fixed.strip():
            q["translation_en"] = fixed.strip()
        if str(m.get("reviewed")).strip() in {"1", "1.0", "x", "X", "True", "true"}:
            q["reviewed"], q["translation_by"] = True, f"{q['translation_by']}; reviewed by the author"
            applied += 1
    return applied


def build_quotes(quotes: list[dict], sheet: Path | None) -> str:
    pending = [q for q in quotes if not q["reviewed"]]
    by_kind: dict[str, list[dict]] = {}
    for q in quotes:
        by_kind.setdefault(q["kind"], []).append(q)
    lines = ["# Portuguese quotations the paper may use", "",
             HEADER_NOTE.replace("`config/paper_numbers.yaml` and ", ""), "",
             "Ground rule 10: every Portuguese quotation that may reach the paper carries a free English translation, and an "
             "LLM-drafted translation is marked as such until the author reviews it. To review, mark `reviewed` = 1 in the "
             "newest `results/quotes_review.xlsx` (write a corrected translation in `translation_en_reviewed` if needed) and "
             "run the script again. Quotations taken directly from the decisions or statutes for the paper are not listed "
             "here and need the same treatment.", "",
             f"**{len(quotes)} quotations; {len(quotes) - len(pending)} with a reviewed translation; {len(pending)} not yet reviewed.**", "",
             "| Source | Quotations | Reviewed |", "| --- | --- | --- |"]
    for kind, qs in by_kind.items():
        lines.append(f"| {kind} | {len(qs)} | {sum(q['reviewed'] for q in qs)} |")
    lines += ["", "## Translations not yet reviewed", ""]
    lines += [f"- `{q['quote_id']}` ({q['kind']}; {q['translation_by']})" for q in pending] or ["None."]
    for kind, qs in by_kind.items():
        lines += ["", f"## {kind}", "", f"Source: `{qs[0]['source']}`.", ""]
        for q in qs:
            status = "reviewed" if q["reviewed"] else "**not reviewed**"
            lines += [f"### `{q['quote_id']}`", "", f"- Location: {q['location']}", f"- Translation: {q['translation_by']} ({status})", "",
                      f"> {q['original_pt']}", "", f"*{q['translation_en']}*" if q["translation_en"] else "*(no translation)*", ""]
    return "\n".join(lines)


def write_review_sheet(quotes: list[dict], previous: Path | None, results: Path) -> Path:
    rows = pd.DataFrame([{c: q.get(c, "") for c in REVIEW_COLUMNS} for q in quotes])
    rows["reviewed"] = rows["reviewed"].map(lambda r: 1 if r is True else "")
    rows["translation_en_reviewed"], rows["comment"] = "", ""
    if previous and previous.exists():
        old = pd.read_excel(previous).set_index("quote_id")
        for i, r in rows.iterrows():
            if r["quote_id"] in old.index and str(old.loc[r["quote_id"], "original_pt"]).strip() == str(r["original_pt"]).strip():
                for c in ("translation_en_reviewed", "comment"):
                    v = old.loc[r["quote_id"], c]
                    rows.at[i, c] = "" if pd.isna(v) else v
    out = new_artefact_path(results / "quotes_review.xlsx")
    with pd.ExcelWriter(out) as xw:
        rows.to_excel(xw, sheet_name="quotes", index=False)
        pd.DataFrame({"how to review": [
            "One row per Portuguese quotation that may reach the paper (results/QUOTES.md).",
            "reviewed: 1 when the English translation is right as written (or as corrected in translation_en_reviewed).",
            "translation_en_reviewed: your translation, if the one given is wrong; leave empty otherwise.",
            "Then run: uv run python scripts/98_results_and_quotes.py"]}).to_excel(xw, sheet_name="README", index=False)
    return out


# =========================================================================================== main

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--review-sheet", action="store_true", help="write a new results/quotes_review.xlsx for the author")
    ap.add_argument("--allow-stale", action="store_true", help="run even if a pinned source is not the newest version")
    args = ap.parse_args()
    S = P.Sources(allow_stale=args.allow_stale)
    problems = S.check()
    if problems and not args.allow_stale:
        raise SystemExit("Pinned sources need attention (config/paper_assets.yaml):\n  " + "\n  ".join(problems))
    results = resolve(load_config("paths")["results"])
    review_sheet = latest_artefact_path(results / "quotes_review.xlsx")
    review_sheet = review_sheet if review_sheet.exists() else None

    with RunManifest(SCRIPT, results, params={"review_sheet": str(review_sheet) if review_sheet else None,
                                              "allow_stale": args.allow_stale, "stale": problems}) as run:
        index = P.manifest_index()
        text, n_numbers = build_results(S, load_config("paper_numbers"), index)
        out = results / "RESULTS.md"
        out.write_text(text, encoding="utf-8")

        quotes = quotes_b3(S) + quotes_a3(S) + quotes_a4(S) + quotes_prompt_specs(S)
        ids = [q["quote_id"] for q in quotes]
        assert len(ids) == len(set(ids)), "quotation IDs are not unique"
        applied = apply_review(quotes, review_sheet)
        qout = results / "QUOTES.md"
        qout.write_text(build_quotes(quotes, review_sheet), encoding="utf-8")

        for name in sorted({n for names in S.used.values() for n in names}):
            run.add_input(S.paths[name])
        if review_sheet:
            run.add_input(review_sheet, role="review marks")
        run.add_output(out, "every number the paper may quote, with its source")
        run.add_output(qout, "every Portuguese quotation the paper may use, with its translation and review state")
        if args.review_sheet:
            sheet = write_review_sheet(quotes, review_sheet, results)
            run.add_output(sheet, "review sheet of the quotations' translations")
            print(f"review sheet -> {P.rel(sheet)}")
        pending = sum(not q["reviewed"] for q in quotes)
        run.data["summary"] = {"numbers": n_numbers, "quotations": len(quotes), "translations_not_reviewed": pending,
                               "review_marks_applied": applied}
        print(f"RESULTS.md: {n_numbers} numbers; QUOTES.md: {len(quotes)} quotations, {pending} translations not reviewed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
